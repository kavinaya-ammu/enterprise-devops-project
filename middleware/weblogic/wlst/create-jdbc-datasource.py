# WLST online template; adapt names, driver and properties to the certified JDBC driver.
import os
admin_url = os.environ.get('WLS_ADMIN_URL')
username = os.environ.get('WLS_USERNAME')
password = os.environ.get('WLS_PASSWORD')
if not all([admin_url, username, password]):
    raise Exception('Set WLS_ADMIN_URL, WLS_USERNAME and WLS_PASSWORD securely')
connect(username, password, admin_url)
try:
    edit(); startEdit()
    ds_name = os.environ.get('WLS_DS_NAME', 'WmsPostgresDS')
    ds_jndi = os.environ.get('WLS_DS_JNDI', 'jdbc/WmsPostgresDS')
    ds_url = os.environ.get('DB_URL', 'jdbc:postgresql://db.example:5432/enterprise_wms')
    ds_user = os.environ.get('DB_USERNAME', 'enterprise_user')
    ds_password = os.environ.get('DB_PASSWORD')
    if not ds_password: raise Exception('Set DB_PASSWORD securely')
    ds = create(ds_name, 'JDBCSystemResource')
    jdbc = ds.getJDBCResource()
    jdbc.setName(ds_name)
    params = jdbc.getJDBCDataSourceParams()
    params.setJNDINames([ds_jndi])
    driver = jdbc.getJDBCDriverParams()
    driver.setUrl(ds_url)
    driver.setDriverName('org.postgresql.Driver')
    driver.setPassword(ds_password)
    props = driver.getProperties().createProperty('user')
    props.setValue(ds_user)
    pool = jdbc.getJDBCConnectionPoolParams()
    pool.setInitialCapacity(1); pool.setMinCapacity(1); pool.setMaxCapacity(20)
    jdbc.getJDBCDataSourceParams().setGlobalTransactionsProtocol('None')
    targets = os.environ.get('WLS_TARGETS', 'AdminServer').split(',')
    assign('JDBCSystemResource', ds_name, 'Target', targets)
    save(); activate(block='true')
finally:
    disconnect()
